"""Launch runs on Kaggle from your own machine with the Kaggle CLI.

    python scripts/kaggle_push.py full_ft --smoke   # one run: RTE 1k seed 1
    python scripts/kaggle_push.py full_ft           # all 16 runs (run_method.sh)
    python scripts/kaggle_push.py --extra lr        # LR search (run_extra.sh)
    python scripts/kaggle_push.py --extra ablation  # ablations (run_extra.sh)

Needs the Kaggle CLI and ~/.kaggle/kaggle.json (kaggle.com/settings -> API).
The repo is private, so instead of cloning from GitHub on Kaggle, this packs
the repo files (everything git tracks or would track, including
results/final/*.json, so finished runs are skipped) into a Kaggle script and
pushes it. If there are uncommitted changes, the results get git_commit
"<hash>-dirty", so commit before the real runs.

Afterwards:
    kaggle kernels status <user>/<slug>
    kaggle kernels output <user>/<slug> -p <dir>
"""  # file description, also shown by --help

from __future__ import annotations  # allows modern type hints on older Python

import argparse  # reads command-line options
import base64  # turns the binary tar.gz into text so it fits inside a Python file
import io  # in-memory file (build the tar.gz without writing to disk)
import json  # writes kernel-metadata.json and reads kaggle.json
import subprocess  # runs git and the kaggle CLI
import sys  # print warnings to stderr
import tarfile  # packs the repo into a .tar.gz
import tempfile  # temp folder for the kernel files
from pathlib import Path  # easy file paths

REPO = Path(__file__).resolve().parent.parent  # this file is scripts/kaggle_push.py, so 2 levels up = repo root
METHODS = ("full_ft", "lora", "adapter", "prompt_tuning")  # allowed method names

KERNEL_TEMPLATE = r'''
# Generated by scripts/kaggle_push.py from commit {commit}. Do not edit here.
import base64, io, os, subprocess, sys, tarfile  # tools needed on Kaggle to unpack and run

CODE = "{code}"  # the whole repo as base64 text (filled in by main)
COMMIT = "{commit}"  # git hash of the uploaded code (filled in by main)
CMDS = {cmds!r}  # list of shell commands to run (filled in by main)

root = "/kaggle/working/peft-showdown"  # folder on Kaggle where the repo is unpacked (working = saved as output)
os.makedirs(root, exist_ok=True)  # create it; exist_ok so a rerun does not crash
tarfile.open(fileobj=io.BytesIO(base64.b64decode(CODE)), mode="r:gz").extractall(root)  # base64 -> bytes -> unpack the repo
os.chdir(root)  # move into the repo; python -m src.train only works from the repo root
env = dict(os.environ, PEFT_GIT_COMMIT=COMMIT, PYTHONUNBUFFERED="1")  # pass commit to results.py (no .git here); unbuffered so logs appear live

def sh(cmd):  # runs one shell command and returns its exit code
    print("\n$ " + cmd, flush=True)  # show the command in the log
    return subprocess.run(cmd, shell=True, env=env).returncode  # run it; 0 means success

sh("nvidia-smi --query-gpu=name,memory.total --format=csv")  # print which GPU we got (should be a T4)
if sh("pip install -q -r requirements.txt") != 0:  # install the pinned libraries
    sys.exit("pip install failed")  # stop: without the libraries every run would fail
# Kaggle ships torchao 0.10; peft 0.21 refuses to build LoRA / prompt tuning
# when an old torchao is installed. We don't use torchao, so remove it.
sh("pip uninstall -y -q torchao")  # remove torchao; without this LoRA and prompt tuning crash on Kaggle
sh("python -c \"import torch, transformers, peft, adapters; "  # quick check that all libraries import ...
   "print('torch', torch.__version__, 'cuda', torch.cuda.is_available(), "  # ... and print their versions
   "'transformers', transformers.__version__, 'peft', peft.__version__, "  # ...
   "'adapters', adapters.__version__)\"")  # ...
code = 0  # overall exit code, 0 = all ok
for c in CMDS:  # each command (e.g. bash scripts/run_method.sh lora)
    code = sh(c) or code  # run it; keep the first non-zero code so a failure is not hidden
print("\nexit code", code)  # final status in the log
'''  # Python script that runs ON Kaggle; main() fills in code, commit and cmds; no curly braces allowed in comments here because of .format()


def git(*args: str) -> str:  # runs a git command in the repo and returns its output
    return subprocess.run(["git", *args], cwd=REPO, check=True,  # cwd=REPO so it works from any folder; check=True -> error if git fails
                          capture_output=True, text=True).stdout.strip()  # capture output as text, remove trailing newline


def kaggle_username() -> str:  # your Kaggle username
    cfg = Path.home() / ".kaggle" / "kaggle.json"  # Kaggle API token file in your home folder
    return json.loads(cfg.read_text())["username"]  # read the "username" field; missing file -> error (you must set up the API token first)


def main() -> None:  # packs the repo and pushes it to Kaggle as a GPU script
    p = argparse.ArgumentParser(description=__doc__,  # --help shows the file description
                                formatter_class=argparse.RawDescriptionHelpFormatter)  # keep its line breaks
    p.add_argument("method", nargs="?", choices=METHODS)  # optional method name (nargs="?" -> may be left out when --extra is used)
    p.add_argument("--extra", choices=("lr", "ablation", "check"),  # run the LR search / ablations instead
                   help="run scripts/run_extra.sh <part> instead of one method")  # text for --help
    p.add_argument("--smoke", action="store_true",  # quick test with one short run
                   help="only RTE 1k seed 1, to check that everything works")  # text for --help
    p.add_argument("--no-push", action="store_true",  # only prepare files, don't upload
                   help="write the kernel folder and print its path, don't push")  # text for --help
    args = p.parse_args()  # read the options
    if not args.method and not args.extra:  # nothing to run?
        p.error("give a method or --extra")  # stop with a usage message

    commit = git("rev-parse", "--short", "HEAD")  # current commit hash, saved in every result
    if git("status", "--porcelain"):  # any uncommitted changes?
        commit += "-dirty"  # mark it, because the uploaded code is not exactly that commit
        print("note: uncommitted changes are uploaded, results get "  # warn the user ...
              f"git_commit={commit}", file=sys.stderr)  # ... on stderr

    files = git("ls-files", "--cached", "--others", "--exclude-standard").splitlines()  # tracked files + new files not in .gitignore
    buf = io.BytesIO()  # in-memory buffer for the tar.gz
    with tarfile.open(fileobj=buf, mode="w:gz") as tar:  # open a gzip tar that writes into the buffer
        for f in files:  # every repo file
            if (REPO / f).is_file():  # skip files that are deleted but still listed by git
                tar.add(REPO / f, arcname=f)  # add with its repo-relative path so the folder layout is kept
    tarball = buf.getvalue()  # the finished tar.gz bytes
    code = base64.b64encode(tarball).decode()  # bytes -> base64 text so it can sit inside run.py

    if args.extra:  # LR search / ablation mode
        cmds = [f"bash scripts/run_extra.sh {args.extra}"]  # command to run on Kaggle
        slug = f"peft-showdown-extra-{args.extra}"  # kernel name on Kaggle
    elif args.smoke:  # smoke-test mode
        cmds = [f"python -m src.train --method {args.method} --task rte "  # one short run (RTE 1k seed 1) ...
                f"--regime 1k --seed 1 --overwrite",  # ... overwrite so it runs even if the result exists
                "python src/results.py results/final/*.json"]  # then validate the result files
        slug = f"peft-showdown-smoke-{args.method.replace('_', '-')}"  # Kaggle names can't contain "_", so use "-"
    else:  # normal mode
        cmds = [f"bash scripts/run_method.sh {args.method}"]  # all 16 final runs for this method
        slug = f"peft-showdown-{args.method.replace('_', '-')}"  # kernel name

    user = kaggle_username()  # your Kaggle user, part of the kernel id
    out = Path(tempfile.mkdtemp(prefix=f"{slug}_"))  # temp folder for run.py + metadata
    (out / "run.py").write_text(  # write the Kaggle script ...
        KERNEL_TEMPLATE.format(code=code, commit=commit, cmds=cmds))  # ... with the repo, commit and commands filled in
    (out / "kernel-metadata.json").write_text(json.dumps({  # settings file the kaggle CLI needs
        "id": f"{user}/{slug}",  # kernel id; same id = new version of the same kernel
        "title": slug,  # title shown on Kaggle
        "code_file": "run.py",  # which file to run
        "language": "python",  # Python script
        "kernel_type": "script",  # a script, not a notebook
        "is_private": True,  # only you can see it
        "enable_gpu": True,  # without GPU training would take days
        "enable_internet": True,  # needed for pip install and downloading the model / data
        "machine_shape": "NvidiaTeslaT4",  # the API only offers T4 x2; src/train.py pins each run to GPU 0
        "dataset_sources": [],  # no Kaggle datasets attached ...
        "competition_sources": [],  # ...
        "kernel_sources": [],  # ...
        "model_sources": [],  # ...
    }, indent=2))  # pretty-print the JSON

    print(f"commit {commit}, {len(tarball) / 1024:.0f} KiB of code -> {out}")  # summary: commit, upload size, folder
    if args.no_push:  # --no-push given
        return  # stop before uploading
    subprocess.run(["kaggle", "kernels", "push", "-p", str(out)], check=True)  # upload and start the kernel; check=True -> error if the push fails
    print(f"\nstatus: kaggle kernels status {user}/{slug}\n"  # how to check progress
          f"output: kaggle kernels output {user}/{slug} -p <dir>\n"  # how to download results
          f"web:    https://www.kaggle.com/code/{user}/{slug}")  # link to the kernel page


if __name__ == "__main__":  # only when run directly, not when imported
    main()  # start
