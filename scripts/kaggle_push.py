"""Launch runs on Kaggle from your own machine with the Kaggle CLI.

    python scripts/kaggle_push.py full_ft --smoke   # one run: RTE 1k seed 1
    python scripts/kaggle_push.py full_ft           # all 16 runs (run_method.sh)

Needs the Kaggle CLI and ~/.kaggle/kaggle.json (kaggle.com/settings -> API).
The repo is private, so instead of cloning from GitHub on Kaggle, this packs
the repo files (everything git tracks or would track, including
results/final/*.json, so finished runs are skipped) into a Kaggle script and
pushes it. If there are uncommitted changes, the results get git_commit
"<hash>-dirty", so commit before the real runs.

Afterwards:
    kaggle kernels status <user>/<slug>
    kaggle kernels output <user>/<slug> -p <dir>
"""

from __future__ import annotations

import argparse
import base64
import io
import json
import subprocess
import sys
import tarfile
import tempfile
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
METHODS = ("full_ft", "lora", "adapter", "prompt_tuning")

KERNEL_TEMPLATE = r'''
# Generated by scripts/kaggle_push.py from commit {commit}. Do not edit here.
import base64, io, os, subprocess, sys, tarfile

CODE = "{code}"
COMMIT = "{commit}"
CMDS = {cmds!r}

root = "/kaggle/working/peft-showdown"
os.makedirs(root, exist_ok=True)
tarfile.open(fileobj=io.BytesIO(base64.b64decode(CODE)), mode="r:gz").extractall(root)
os.chdir(root)
env = dict(os.environ, PEFT_GIT_COMMIT=COMMIT, PYTHONUNBUFFERED="1")

def sh(cmd):
    print("\n$ " + cmd, flush=True)
    return subprocess.run(cmd, shell=True, env=env).returncode

sh("nvidia-smi --query-gpu=name,memory.total --format=csv")
if sh("pip install -q -r requirements.txt") != 0:
    sys.exit("pip install failed")
sh("python -c \"import torch, transformers, peft, adapters; "
   "print('torch', torch.__version__, 'cuda', torch.cuda.is_available(), "
   "'transformers', transformers.__version__, 'peft', peft.__version__, "
   "'adapters', adapters.__version__)\"")
code = 0
for c in CMDS:
    code = sh(c) or code
print("\nexit code", code)
'''


def git(*args: str) -> str:
    return subprocess.run(["git", *args], cwd=REPO, check=True,
                          capture_output=True, text=True).stdout.strip()


def kaggle_username() -> str:
    cfg = Path.home() / ".kaggle" / "kaggle.json"
    return json.loads(cfg.read_text())["username"]


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("method", choices=METHODS)
    p.add_argument("--smoke", action="store_true",
                   help="only RTE 1k seed 1, to check that everything works")
    p.add_argument("--no-push", action="store_true",
                   help="write the kernel folder and print its path, don't push")
    args = p.parse_args()

    commit = git("rev-parse", "--short", "HEAD")
    if git("status", "--porcelain"):
        commit += "-dirty"
        print("note: uncommitted changes are uploaded, results get "
              f"git_commit={commit}", file=sys.stderr)

    files = git("ls-files", "--cached", "--others", "--exclude-standard").splitlines()
    buf = io.BytesIO()
    with tarfile.open(fileobj=buf, mode="w:gz") as tar:
        for f in files:
            if (REPO / f).is_file():
                tar.add(REPO / f, arcname=f)
    tarball = buf.getvalue()
    code = base64.b64encode(tarball).decode()

    if args.smoke:
        cmds = [f"python -m src.train --method {args.method} --task rte "
                f"--regime 1k --seed 1 --overwrite",
                "python src/results.py results/final/*.json"]
        slug = f"peft-showdown-smoke-{args.method.replace('_', '-')}"
    else:
        cmds = [f"bash scripts/run_method.sh {args.method}"]
        slug = f"peft-showdown-{args.method.replace('_', '-')}"

    user = kaggle_username()
    out = Path(tempfile.mkdtemp(prefix=f"{slug}_"))
    (out / "run.py").write_text(
        KERNEL_TEMPLATE.format(code=code, commit=commit, cmds=cmds))
    (out / "kernel-metadata.json").write_text(json.dumps({
        "id": f"{user}/{slug}",
        "title": slug,
        "code_file": "run.py",
        "language": "python",
        "kernel_type": "script",
        "is_private": True,
        "enable_gpu": True,
        "enable_internet": True,
        # the API only offers T4 x2; src/train.py pins each run to GPU 0
        "machine_shape": "NvidiaTeslaT4",
        "dataset_sources": [],
        "competition_sources": [],
        "kernel_sources": [],
        "model_sources": [],
    }, indent=2))

    print(f"commit {commit}, {len(tarball) / 1024:.0f} KiB of code -> {out}")
    if args.no_push:
        return
    subprocess.run(["kaggle", "kernels", "push", "-p", str(out)], check=True)
    print(f"\nstatus: kaggle kernels status {user}/{slug}\n"
          f"output: kaggle kernels output {user}/{slug} -p <dir>\n"
          f"web:    https://www.kaggle.com/code/{user}/{slug}")


if __name__ == "__main__":
    main()
